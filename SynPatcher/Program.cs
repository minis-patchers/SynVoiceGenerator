    static bool IsValidChar(char x) => Char.IsAsciiLetterOrDigit(x) || x == '-' || x == '=' || x == '$' || x == '<' || x == '>' || x == ' ' || x == '.' || x == ',' || x == '?' || x == '!' || x == '\"' || x == '\'' || x == '*' || x == '[' || x == ']' || x == '(' || x == ')';
    static string CleanString(string str) => new string(REG.HiddenFN2.Replace(REG.HiddenFN.Replace(str, ""), "").Where(IsValidChar).ToArray()).Trim();
    static void Patch(IPatcherState<ISkyrimMod, ISkyrimModGetter> state)
    {
        JsonSerializerSettings settings = new();
        settings.AddMutagenConverters();
        settings.Formatting = Formatting.Indented;
        EDFP = state.ExtraSettingsDataPath ?? string.Empty;
        var parent = Directory.GetParent(state.DataFolderPath);
        CKTools = Path.Join(parent?.FullName, "Tools");
        Directory.CreateDirectory(Path.Join(state.ExtraSettingsDataPath, "tmp"));
        if (!File.Exists(Path.Join(state.ExtraSettingsDataPath, "ffmpeg.exe")))
        {
            if (!File.Exists(Path.Join(state.ExtraSettingsDataPath, "tmp", "FFMPEG.zip")))
            {
                DownloadFileAsync("https://github.com/BtbN/FFmpeg-Builds/releases/download/latest/ffmpeg-n7.1-latest-win64-gpl-7.1.zip", Path.Join(state.ExtraSettingsDataPath, "tmp", "FFMPEG.zip")).Wait();
                using var zip = ZipFile.OpenRead(Path.Join(state.ExtraSettingsDataPath, "tmp", "FFMPEG.zip"));
                var ent = zip.Entries.Where(x => x.Name == "ffmpeg.exe").First();
                ent.ExtractToFile(Path.Join(state.ExtraSettingsDataPath, "ffmpeg.exe"));
            }
        }
        if (!File.Exists(Path.Join(state.ExtraSettingsDataPath, "FaceFXWrapper.exe")))
        {
            DownloadFileAsync("https://github.com/Nukem9/FaceFXWrapper/releases/download/0.41/FaceFXWrapper.0.41.zip", Path.Join(state.ExtraSettingsDataPath, "tmp", "facefx.zip")).Wait();
            using var zip = ZipFile.OpenRead(Path.Join(state.ExtraSettingsDataPath, "tmp", "facefx.zip"));
            var ffxw = zip.Entries.Where(x => x.Name == "FaceFXWrapper.exe").First();
            ffxw.ExtractToFile(Path.Join(state.ExtraSettingsDataPath, "FaceFXWrapper.exe"));
        }
        if (!File.Exists("FonixData.cdf"))
        {
            File.Copy(Path.Join(CKTools, "LipGen", "LipGenerator", "FonixData.cdf"), "FonixData.cdf");
        }

        var voice_directory = Path.Join(state.DataFolderPath, "Sound", "VPC", "DefaultVoice");
        var voice_sound = Path.Join(voice_directory, "Voice");
        var voice_data = Path.Join(voice_directory, "Data");
        if (Directory.Exists(voice_data))
        {
            foreach (var dir in Directory.EnumerateDirectories(voice_data))
            {
                var fn = new DirectoryInfo(dir).Name;
                Log($"Loading files for {fn}", LogMode.NORMAL);
                if (!state.LoadOrder.ModExists(fn)) continue;
                foreach (var file in Directory.EnumerateFiles(dir))
                {
                    if (file.EndsWith(".json"))
                    {
                        var form = Path.GetFileNameWithoutExtension(file);
                        var fk = FormKey.Factory($"{form}:{fn}");
                        if (state.LinkCache.TryResolve<IDialogTopicGetter>(fk, out var vt))
                        {
                            var n = CleanString($"{vt.Name}");
                            if (n.IsNullOrEmpty()) continue;
                            Log($"Loading entry for {fk}: {CleanString($"{vt.Name}")}", LogMode.DEBUG);
                            if (lines.ContainsKey(n))
                            {
                                var lin = lines[n];
                                var varint = JsonConvert.DeserializeObject<HashSet<VariantData>>(File.ReadAllText(file), settings)!;
                                Log($"Merging {lin.forms.First()} with {lin.variants.Count} variants with {fk} containing text {CleanString($"{vt.Name}")} and {varint.Count} variants", LogMode.DEBUG);
                                lin.forms.Add(fk);
                                lin.variants.Add(varint);
                                lin.variants = lin.variants.DistinctBy(x => x.guid).ToHashSet();
                                Log($"Final Variant Count {lin.variants.Count}", LogMode.DEBUG);
                            }
                            else
                            {
                                var lt = new LineTracker();
                                lt.forms.Add(fk);
                                lt.variants = JsonConvert.DeserializeObject<HashSet<VariantData>>(File.ReadAllText(file), settings)!;
                                if (lt.variants.Count > 0)
                                {
                                    lines[n] = lt;
                                }
                            }
                        }
                    }
                }
            }
        }
        var vgroot = Path.Join(EDFP, "VGOutput");
        mp3 = Path.Join(vgroot, "mp3");
        wav = Path.Join(vgroot, "wav");
        lip = Path.Join(vgroot, "lip");
        xwm = Path.Join(vgroot, "xwm");
        fuz = Path.Join(vgroot, "fuz");
        Directory.CreateDirectory(mp3);
        Directory.CreateDirectory(wav);
        Directory.CreateDirectory(lip);
        Directory.CreateDirectory(xwm);
        Directory.CreateDirectory(fuz);
        client.BaseAddress = new Uri($"http://localhost:8000");
        var gens = state.LoadOrder.PriorityOrder.DialogTopic().WinningOverrides().Where(x => $"{x.Name}" != x.EditorID && x.Category == DialogTopic.CategoryEnum.Topic).Where(x => !$"{CleanString($"{x.Name}")}".IsNullOrEmpty() && $"{x.Name}" != $"{x.EditorID}").Select(x => (CleanString($"{x.Name}"), x.FormKey));
        var totalCount = gens.DistinctBy(x => x.Item1).Count();
        var genc = lines.Count;
        Log($"{totalCount} potential dialogue lines found and {lines.Count} are currently generated, generating {totalCount - lines.Count} lines of dialogue. This could take a while.", LogMode.NORMAL);
        foreach (var (Name, FormKey) in gens)
        {
            try
            {
                if (!lines.ContainsKey(Name))
                {
                    genc++;
                }
                ProcLine(Name, FormKey);
                if (genc % APIInfo.print_every_gen == 0)
                {
                    Log($"Generation Progress {genc}/{totalCount} (Estimated)", LogMode.NORMAL);
                }
            }
            catch (Exception ex)
            {
                Log($"Generation Progress {genc}/{totalCount} (Estimated)", LogMode.NORMAL);
                Log($"{ex.Message}", LogMode.NORMAL);
                break;
            }
        }
        var rem = lines.Where(x => x.Value.variants.Count == 0).Select(x => x.Key).ToHashSet();
        rem.ForEach(x => lines.Remove(x));
        Log($"Removed {rem.Count} objects with no variants", LogMode.NORMAL);
        Log($"Writing {lines.Sum(x => x.Value.forms.Count)} json items for VPC-SKSE for {lines.Sum(x => x.Value.variants.Count)} variants", LogMode.NORMAL);
        Directory.CreateDirectory(voice_sound);
        Directory.CreateDirectory(voice_data);

        var files = lines.SelectMany(x => x.Value.forms).Select(x => x.ModKey.ToString()).Distinct().ToHashSet();
        foreach (var fil in files)
        {
            Directory.CreateDirectory(Path.Join(voice_data, fil));
        }

        var variants = lines.SelectMany(x => x.Value.variants).ToHashSet();
        Log($"Copying {variants.Count} fuz files", LogMode.NORMAL);
        foreach (var vd in variants)
        {
            var fp = Path.Join(voice_sound, $"{vd.guid}.fuz");
            var ep = Path.Join(state.ExtraSettingsDataPath, "VGOutput", "fuz", $"{vd.guid}.fuz");
            if (!File.Exists(fp) && File.Exists(ep))
            {
                Log($"Copying {vd.guid} to Game Path", LogMode.DEBUG);
                File.Copy(ep, fp, true);
            }
        }

        Log($"Writing {lines.Sum(x => x.Value.forms.Count)} json files", LogMode.NORMAL);
        foreach (var line in lines)
        {
            foreach (var id in line.Value.forms)
            {
                var jso = Path.Join(voice_data, id.ModKey.ToString(), $"{id.IDString()}.json");
                if (line.Value.variants.Count > 0)
                {
                    Log($"Writing {jso}", LogMode.DEBUG);
                    File.WriteAllText(jso, JsonConvert.SerializeObject(line.Value.variants, settings));
                }
                else
                {
                    try
                    {
                        File.Delete(jso);
                    }
                    catch
                    { }
                }
            }
        }
    }
    static void ProcLine(string Name, FormKey FormKey)
    {
        var line = lines.GetOrAdd(Name, () => new()
        {
            forms = [FormKey],
            variants = [],
        });
        if (line.variants.Count > 0 && line.variants.All(x => x.reg_frags == null))
        {
            line.forms.Add(FormKey);
            Log($"Skipping {Name}", LogMode.NORMAL);
            return;
        }
        //Basic Text Line
        if (!Name.Contains('<') && !Name.Contains('>') && !(Name.StartsWith('(') && Name.EndsWith(')')) && !(Name.StartsWith('[') && !Name.EndsWith(']')) && !(Name.EndsWith('*') && Name.StartsWith('*')) && !Name.Contains('_') && Name != "..." && !Name.StartsWith('$'))
        {
            var dat = Generate(Name);
            if (dat != null)
            {
                line.variants.Add(new()
                {
                    guid = dat.Value.guid,
                    splen = dat.Value.splen,
                    reg_frags = null,
                });
            }
        }
        //One of many different possible type variant data.
        else
        {
            if (Name != "...")
            {
                var vc = line.variants.Count;
                var cont = APIInfo.replacementLists.Where(x => Name.Contains($"<{x.Key}>")).ToDictionary();
                foreach (var (vd, tline) in cont.GenerateTemplatedCartesianProduct(Name))
                {
                    Log($"{tline}", LogMode.NORMAL);
                    if (!tline.Contains('<') && !tline.Contains('>') && !vd.All(x => line.variants.Any(y => y.reg_frags?.Contains(x) ?? false)))
                    {
                        var ld = Generate(tline);
                        if (ld != null)
                        {
                            line.variants.Add(new()
                            {
                                guid = ld.Value.guid,
                                splen = ld.Value.splen,
                                reg_frags = vd,
                            });
                        }
                    }
                }
            }
        }
        return;
    }

    static void Log(string lt, LogMode md)
    {
        if (APIInfo.log_mode >= md)
        {
            Console.WriteLine(lt);
        }
    }
    static LineData? Generate(string text)
    {
        var guid = Guid.NewGuid().ToString().ToUpper();
        while (lines.Any(x => x.Value.variants.Any(x => x.guid == $"{guid}")) || File.Exists(Path.Join(EDFP, "VGOutput", "fuz", $"{guid}.fuz")))
        {
            Log("Regenerating identical guid", LogMode.DEBUG);
            guid = Guid.NewGuid().ToString().ToUpper();
        }
        var mp3name = Path.Join(mp3, $"{guid}.mp3");
        var wavname = Path.Join(wav, $"{guid}.wav");
        var rwavnam = Path.Join(wav, $"{guid}.resamp.wav");
        var lipname = Path.Join(lip, $"{guid}.lip");
        var xwmname = Path.Join(xwm, $"{guid}.xwm");
        var fuzname = Path.Join(fuz, $"{guid}.fuz");
        if (!File.Exists(mp3name) && !File.Exists(fuzname))
        {
            Log($"Generating: {text}", LogMode.NORMAL);
            StringContent stringContent = new(JsonConvert.SerializeObject(new Request(text, APIInfo)), Encoding.UTF8, "application/json");
            var cli = client.PostAsync($"/speak", stringContent);
            cli.Wait();
            if (cli.Result.IsSuccessStatusCode)
            {
                var file = File.OpenWrite(wavname);
                cli.Result.Content.CopyTo(file, null, CancellationToken.None);
                file.Close();
            }
            else
            {
                Log($"error: {cli.Result.StatusCode}", LogMode.NORMAL);
                throw new Exception(cli.Result.Content.ToString());
            }
        }
        if (!File.Exists(fuzname) && File.Exists(wavname))
        {

            var p = new ProcessStartInfo($"{EDFP}/ffmpeg.exe");
            p.Arguments = $"-i \"{wavname}\" -ac 1 \"{mp3name}\"";
            p.RedirectStandardError = true;
            p.RedirectStandardInput = true;
            p.RedirectStandardOutput = true;
            var d = Process.Start(p);
            d!.WaitForExit();
            LineData ret = new()
            {
                guid = guid,
                splen = Exts.GetMp3Duration(mp3name),
            };
            p.FileName = $"{EDFP}/FaceFXWrapper.exe";
            p.Arguments = $"Skyrim USEnglish FonixData.cdf \"{wavname}\" \"{rwavnam}\" \"{lipname}\" \"{text.Replace("\"", "\\\"")}\"";
            d = Process.Start(p);
            d!.WaitForExit();
            p.FileName = $"{EDFP}/xWMAEncode.exe";
            p.Arguments = $"\"{wavname}\" \"{xwmname}\"";
            d = Process.Start(p);
            d!.WaitForExit();
            p.FileName = $"{EDFP}/BmlFuzEncode.exe";
            p.Arguments = $"\"{fuzname}\" \"{xwmname}\" \"{lipname}\"";
            d = Process.Start(p);
            d!.WaitForExit();
            Log($"Generated {text}", LogMode.NORMAL);
            return ret;
        }
        else
        {
            Log($"Skipping {text}", LogMode.NORMAL);
        }
        return null;
    }
