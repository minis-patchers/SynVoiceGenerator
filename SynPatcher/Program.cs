    static bool IsValidChar(char x) => Char.IsAsciiLetterOrDigit(x) || x == '-' || x == '=' || x == '$' || x == '<' || x == '>' || x == ' ' || x == '.' || x == ',' || x == '?' || x == '!' || x == '\"' || x == '\'' || x == '*' || x == '[' || x == ']' || x == '(' || x == ')';
    static string CleanString(this string str) => new string([.. REG.HiddenFN2.Replace(REG.HiddenFN.Replace(str, ""), "").Where(IsValidChar)]).Trim().TrimEnd(',').Replace("\n", " ").Replace("\r", " ").Replace("\t", " ").Replace("  ", " ").TrimEnd(' ');
    static string RemovePunct(this string str) => str.Replace(".", "").Replace("!", "").Replace("?", "").Replace(",", "").Replace("\"", "").Replace("\'", "");
    static void Patch(IPatcherState<ISkyrimMod, ISkyrimModGetter> state)
    {
        JsonSerializerSettings settings = new();
        settings.AddMutagenConverters();
        settings.Formatting = Formatting.Indented;
        EDFP = state.ExtraSettingsDataPath ?? string.Empty;
        var parent = Directory.GetParent(state.DataFolderPath);
        CKTools = Path.Join(parent?.FullName, "Tools");
        Directory.CreateDirectory(Path.Join(state.ExtraSettingsDataPath, "tmp"));
        if (!File.Exists(Path.Join(state.ExtraSettingsDataPath, "ffmpeg.exe")))
        {
            if (!File.Exists(Path.Join(state.ExtraSettingsDataPath, "tmp", "FFMPEG.zip")))
            {
                DownloadFileAsync("https://github.com/BtbN/FFmpeg-Builds/releases/download/latest/ffmpeg-n8.1-latest-win64-gpl-8.1.zip", Path.Join(state.ExtraSettingsDataPath, "tmp", "FFMPEG.zip")).Wait();
                using var zip = ZipFile.OpenRead(Path.Join(state.ExtraSettingsDataPath, "tmp", "FFMPEG.zip"));
                var ent = zip.Entries.Where(x => x.Name == "ffmpeg.exe").First();
                ent.ExtractToFile(Path.Join(state.ExtraSettingsDataPath, "ffmpeg.exe"));
            }
        }
        if (!File.Exists(Path.Join(state.ExtraSettingsDataPath, "FaceFXWrapper.exe")))
        {
            DownloadFileAsync("https://github.com/Nukem9/FaceFXWrapper/releases/download/0.41/FaceFXWrapper.0.41.zip", Path.Join(state.ExtraSettingsDataPath, "tmp", "facefx.zip")).Wait();
            using var zip = ZipFile.OpenRead(Path.Join(state.ExtraSettingsDataPath, "tmp", "facefx.zip"));
            var ffxw = zip.Entries.Where(x => x.Name == "FaceFXWrapper.exe").First();
            ffxw.ExtractToFile(Path.Join(state.ExtraSettingsDataPath, "FaceFXWrapper.exe"));
        }
        if (!File.Exists("FonixData.cdf"))
        {
            File.Copy(Path.Join(CKTools, "LipGen", "LipGenerator", "FonixData.cdf"), "FonixData.cdf");
        }

        var voice_directory = Path.Join(state.DataFolderPath, "Sound", "VPC", "DefaultVoice");
        var voice_sound = Path.Join(voice_directory, "Voice");
        var voice_data = Path.Join(voice_directory, "Data");
        if (Directory.Exists(voice_data))
        {
            foreach (var dir in Directory.EnumerateDirectories(voice_data))
            {
                var fn = new DirectoryInfo(dir).Name;
                Log($"Loading files for {fn}", LogMode.NORMAL);
                if (!state.LoadOrder.ModExists(fn)) continue;
                foreach (var file in Directory.EnumerateFiles(dir))
                {
                    if (file.EndsWith(".json"))
                    {
                        var form = Path.GetFileNameWithoutExtension(file);
                        var fk = FormKey.Factory($"{form}:{fn}");
                        if (state.LinkCache.TryResolve<IDialogTopicGetter>(fk, out var vt))
                        {
                            var n = $"{vt.Name}".CleanString();
                            if (n.IsNullOrEmpty()) continue;
                            Log($"Loading entry for {fk}: {$"{vt.Name}".CleanString()}", LogMode.DEBUG);
                            var lind = lines.Where(x => x.forms.Any(x => state.LinkCache.TryResolve<IDialogTopicGetter>(x, out var dg) && dg != null && $"{dg.Name}".CleanString() == n));
                            if (lind.Any())
                            {
                                var lin = lind.First();
                                HashSet<VariantData> nvd;
                                try
                                {
                                    nvd = JsonConvert.DeserializeObject<HashSet<VariantData>>(File.ReadAllText(file), settings)!;
                                }
                                catch (Exception)
                                {
                                    Log("Loading potentially old variant file, discarding variants requiring text data.", LogMode.NORMAL);
                                    var varint = JsonConvert.DeserializeObject<HashSet<OldVariantData>>(File.ReadAllText(file), settings)!;
                                    nvd = varint.Where(x => x.reg_frags == null).Select(x => new VariantData
                                    {
                                        guid = x.guid,
                                        reg_frags = null,
                                        splen = x.splen
                                    }).ToHashSet();
                                    Log($"Removing {varint.Count(x => x.reg_frags != null)} variants", LogMode.NORMAL);
                                }
                                Log($"Merging {lin.forms.First()} with {lin.variants.Count} variants with {fk} containing text {$"{vt.Name}".CleanString()} and {nvd.Count} variants", LogMode.DEBUG);
                                lin.forms.Add(fk);
                                lin.variants.Add(nvd);
                                lin.variants = lin.variants.DistinctBy(x => x.guid).ToHashSet();
                                Log($"Final Variant Count {lin.variants.Count}", LogMode.DEBUG);
                            }
                            else
                            {
                                var lt = new LineTracker();
                                lt.forms.Add(fk);
                                try
                                {
                                    lt.variants = JsonConvert.DeserializeObject<HashSet<VariantData>>(File.ReadAllText(file), settings)!;
                                }
                                catch (Exception)
                                {
                                    Log("Loading potentially old variant file, discarding variants requiring text data.", LogMode.NORMAL);
                                    var varint = JsonConvert.DeserializeObject<HashSet<OldVariantData>>(File.ReadAllText(file), settings)!;
                                    lt.variants = varint.Where(x => x.reg_frags == null).Select(x => new VariantData
                                    {
                                        guid = x.guid,
                                        reg_frags = null,
                                        splen = x.splen
                                    }).ToHashSet();
                                    Log($"Removing {varint.Count(x => x.reg_frags != null)} variants", LogMode.NORMAL);
                                }
                                if (lt.variants.Count > 0)
                                {
